def _resolve_root():
    return _store().resolve_root()


def _require_root():
    """root, or raises bm_store.OwnershipRefused('no-root', ...) naming the
    exact fix. Every ownership command uses this; advisory commands use
    _resolve_root() instead and degrade instead of raising."""
    return _store().require_root()[0]


def _threads_dir(root):
    return os.path.join(root, THREADS_DIRNAME)


def _mode_path(root):
    return os.path.join(_threads_dir(root), MODE_FILE)


def _atomic_write(path, text):
    """Crash-atomic whole-file replacement (temp file + os.replace), the same
    shape bm_store._atomic_write_text uses. Returns True/False, never raises:
    every caller here is a boundary that must report failure honestly rather
    than let an exception look like a swallowed success."""
    d = os.path.dirname(os.path.abspath(path)) or "."
    try:
        os.makedirs(d, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix=".bm_threads.", dir=d)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                f.write(text)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, path)
        except OSError:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise
        return True
    except OSError:
        return False


def _read(path):
    try:
        with io.open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _load_mode(root):
    """The mode file: mode ("on"/"off"), since, and a purely descriptive
    history. It holds NOTHING about who owns what work; that question always
    goes to the store. Anything unreadable or malformed reads as an empty,
    OFF mode, so a hand-edited file cannot make every command raise."""
    try:
        d = json.loads(_read(_mode_path(root)) or "{}")
    except Exception:
        return {"mode": "off"}
    if not isinstance(d, dict):
        return {"mode": "off"}
    if d.get("mode") not in ("on", "off"):
        d["mode"] = "off"
    return d


def _save_mode(root, d):
    return _atomic_write(_mode_path(root), json.dumps(d, indent=2, sort_keys=True) + "\n")


def _history(d):
    if not isinstance(d.get("history"), list):
        d["history"] = []
    return d["history"]


# ---------------------------------------------------------------------------
# Output funnel: redact before anything founder-typed (an objective, a
# refusal message quoting a name) reaches stdout. Mirrors bm_store.py's own
# _out/_warn split (fail CLOSED on stdout for ownership text, fail OPEN on
# stderr for advisories) at the scale this smaller CLI actually needs: one
# protected printer plus one pass-through for text a render function already
# protected field-by-field (the dashboard).
# ---------------------------------------------------------------------------

def _protect(s):
    return _store().redact_text(s or "")


def _out(s, end="\n"):
    """THE stdout funnel for founder-influenced text. Refuses (propagates
    RedactionUnavailable to main(), non-zero exit) rather than print anything
    if the redactor cannot be loaded: an ownership-adjacent message must fail
    closed, not print unprotected on the one occasion redaction is broken."""
    sys.stdout.write(_protect(s) + end)
    sys.stdout.flush()


def _out_prerendered(s, end=""):
    """For text a store render function (render_state_md) already redacted
    field by field. Re-running _protect over it would be redundant at best
    and, because that document's own newlines are structure, corrosive at
    worst (mirrors bm_store.py's own _out_prerendered)."""
    sys.stdout.write(s + end)
    sys.stdout.flush()


def _warn(s, end="\n"):
    """THE stderr funnel: advisory, fails OPEN. Degrades to a fixed notice
    instead of raising when the redactor is unavailable, so a broken
    redactor can never silence every warning in the program."""
    bs = _store()
    try:
        safe = _protect(s)
    except bs.RedactionUnavailable:
        sys.stderr.write("bm_threads: WARNING: could not load the redactor; "
                          "a warning was suppressed rather than print unprotected text.\n")
        return
    sys.stderr.write(safe + end)


