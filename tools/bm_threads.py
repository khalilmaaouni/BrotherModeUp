def cmd_recommend(argv):
    """Advice ONLY. Never touches the mode file: a surprise mode change
    mid-project is exactly the disruption the founder ruled out."""
    root, _source = _resolve_root()
    mode = _load_mode(root) if root else {"mode": "off"}
    if mode.get("mode") == "on":
        _out("thread mode is already ON. `bm_threads.py off` drains and parks it.")
        return
    n = None
    if argv:
        try:
            n = int(argv[0])
        except ValueError:
            n = None
    if n is None:
        n = 0
        if root is not None:
            try:
                store = _store().Store(root, create=False)
                try:
                    n = sum(1 for r in _records_by_identity(store)
                            if r.state == "active" and r.lifetime == "persistent")
                finally:
                    store.close()
            except Exception:
                n = 0
    if n >= 3:
        _out("RECOMMENDATION: %d parallel features detected or declared. Thread mode "
             "pays off at 3 or more (each thread keeps its own context, the chief "
             "stays small and stops compacting)." % n)
        _out("  turn it on:  python3 tools/bm_threads.py on")
        _out("  it stays off until you run that. Nothing flips by itself.")
    else:
        _out("RECOMMENDATION: stay single-orchestrator (%d feature(s)). Below 3 "
             "parallel features the per-thread overhead costs more than it saves." % n)


def cmd_on(argv):
    bs = _store()
    root, source = _resolve_root()
    if root is None:
        # Mirrors bm_store.py's own `init`: the one command allowed to
        # proceed with no root, because its job is to create the anchor.
        root = os.path.realpath(os.getcwd())
        source = "cwd (nothing found to anchor on; this becomes the new root)"
    bs.Store(root, create=True).close()  # establishes .brothermode/store.sqlite3
    d = _load_mode(root)
    if d.get("mode") == "on":
        _out("thread mode already ON since %s" % d.get("since", "?"))
        return
    d["mode"] = "on"
    d["since"] = now()
    _history(d).append({"ts": now(), "event": "on"})
    if not _save_mode(root, d):
        raise bs.OwnershipRefused(
            "mode-write-failed",
            "thread-mode.json is not writable; nothing was turned on.")
    _out("thread mode ON. Cap: %d active persistent thread(s) (enforced by the store)."
         % bs.MAX_ACTIVE_PERSISTENT)
    _out("  root resolved via %s" % source)
    _out("  start one:  python3 tools/bm_threads.py start <feature> \"<objective>\"")
    _out("  review all: python3 tools/bm_threads.py dashboard")


def cmd_off(argv):
    bs = _store()
    root = _require_root()
    d = _load_mode(root)
    if d.get("mode") != "on":
        _out("thread mode is already OFF.")
        return
    store = bs.Store(root, create=False)
    try:
        # Authoritative rows, never dump()'s presentation view (FINDING 9;
        # see _records_by_identity for why a DISPLAY allowlist must not be
        # what decides which records get drained).
        candidates = [r for r in _records_by_identity(store)
                      if r.state == "active" and r.lifetime == "persistent"]
        if not candidates:
            d["mode"] = "off"
            _history(d).append({"ts": now(), "event": "off", "drained": []})
            if not _save_mode(root, d):
                # _out + sys.exit, not raise: matches every other honest-failure
                # path in this command (below) rather than a one-off exception,
                # so a caller in-process gets the same reporting shape either way.
                _out("MODE FILE NOT UPDATED: no active thread needed draining, "
                     "but thread-mode.json could not be written to OFF.")
                sys.exit(2)
            _out("thread mode OFF (nothing to absorb: no active persistent threads).")
            return
        drained, failed = [], []
        for rec in candidates:
            luid, ver, sid = rec.lifecycle_uuid, rec.version, rec.session_id
            # The authoritative name is founder-typed text, so it is
            # protected ONCE here and only the protected form is used below:
            # the heading goes into STATE.md (exactly like cmd_adopt), and
            # the drained list is both printed and written into
            # thread-mode.json's history. dump() used to redact this field
            # on the way in; reading the real row means this module does it
            # itself, at the boundary where it belongs.
            safe_name = _protect(rec.name)
            # LOOP P12: ONE call. The park and its handover are one sqlite
            # transaction, so this loop can no longer produce the two states
            # that used to be reachable here: a record parked with its handover
            # missing (the append lost to a concurrent rewrite), or a handover
            # delivered for a park the store then refused. Whatever this raises,
            # the record is exactly where it was and no handover exists for it.
            try:
                store.transition(
                    luid, ver, "parked", session_id=sid,
                    note="drained by thread-mode off",
                    handover_heading="Drained from thread mode: %s" % safe_name)
                drained.append(safe_name)
            except (bs.StaleIdentity, bs.OwnershipRefused) as e:
                failed.append((safe_name, luid, str(e)))
        # The view is a pure render of what just committed, so a failure here
        # loses nothing: every drained handover is a row in the store, and the
        # next command regenerates the file.
        try:
            bs.write_state_view(root)
        except Exception as e:
            _warn("bm_threads: could not refresh STATE.md's generated view (%r); "
                  "every drained handover is in the store regardless (see "
                  "`python3 tools/bm_store.py handovers`)." % (e,))
        if failed:
            _out("HANDOVER INCOMPLETE: %d of %d active thread(s) could not be drained:"
                 % (len(failed), len(candidates)))
            for name, luid, reason in failed:
                _out("  - %s (%s): %s" % (name, luid[:8], reason))
            _out("  Thread mode stays ON. %d thread(s) were parked; the rest stay "
                 "ACTIVE so nothing is lost. Fix the issue and run `off` again."
                 % len(drained))
            sys.exit(2)
        d["mode"] = "off"
        _history(d).append({"ts": now(), "event": "off", "drained": drained})
        if not _save_mode(root, d):
            _out("HANDOVER SAFE, MODE FILE NOT UPDATED: %d thread(s) were drained "
                 "and parked, so nothing is lost, but thread-mode.json could not be "
                 "written and still says ON." % len(drained))
            _out("  Fix that file, then run `off` again; re-draining is a no-op "
                 "because every record is already parked.")
            sys.exit(2)
        _out("thread mode OFF (drained and parked %d thread(s), nothing deleted)."
             % len(drained))
        for name in drained:
            _out("    - %s" % name)
        _out("  threads remain on disk under %s/ and are resumable." % THREADS_DIRNAME)
    finally:
        store.close()


def cmd_start(argv):
    bs = _store()
    root = _require_root()
    d = _load_mode(root)
    if d.get("mode") != "on":
        _out("thread mode is OFF. Run `on` first (nothing starts implicitly).")
        sys.exit(2)
    if not argv:
        _out("usage: start <feature-name> \"<objective>\" [--files <path> ...] "
             "[--session SID] [--tier T]")
        sys.exit(2)
    name = argv[0]
    # The objective is POSITIONAL text (V1's ergonomics: no quoting a
    # multi-word objective behind an --objective flag), so it runs from
    # argv[1] up to the first recognised flag; everything from there on is
    # ordinary "--flag value..." parsing via _parse_kv.
    flag_names = ("--files", "--session", "--tier")
    # GATE 5 (release-blockers spec, 2026-07-26): an unrecognized "--xxx"
    # token used to be silently swallowed into the positional objective
    # text, since it never matched flag_names and so never bounded the
    # objective at all -- reproduced with `start X --file f` (singular),
    # which created a thread with NO FENCE at exit 0. Every "--"-shaped
    # token in argv[1:] must be a RECOGNIZED flag before any of it is
    # treated as either objective prose or a flag's value.
    unknown = _unrecognized_start_flags(argv[1:], flag_names)
    if unknown:
        _out("start: unrecognized flag(s) %s (recognized: %s)"
             % (", ".join(unknown), ", ".join(flag_names)))
        sys.exit(2)
    flag_at = min([argv.index(f) for f in flag_names if f in argv[1:]] or [len(argv)])
    objective = " ".join(argv[1:flag_at]).strip() or "(objective not stated)"
    kv = _parse_kv(argv[flag_at:])
    files = kv.get("files", [])
    session_id = " ".join(kv.get("session", [])) or _default_session_id()
    tier = " ".join(kv.get("tier", [])) or "T2"
    store = bs.Store(root, create=False)
    try:
        rec = store.claim(name, "persistent", objective, files or None,
                           session_id=session_id, tier=tier, cwd=os.getcwd())
        digest_text = store.render_digest(rec.lifecycle_uuid)
    finally:
        store.close()
    _refresh_root_view(root)
    base = _thread_dir(root, name, rec.lifecycle_uuid)
    # The CLI-typed name and objective are founder-typed text, and these
    # files are plain views on disk (not a store render function that
    # already redacts internally, the way render_digest does), so they go
    # through the same protect-before-write funnel as everything else this
    # module writes, exactly like the outbox.md line checkpoint appends.
    # valid_name accepts a name shaped like a real secret (bm_store's own
    # round-7 fix note says so explicitly), so the name is never assumed
    # safe just because it passed that check.
    safe_name = _protect(name)
    safe_objective = _protect(objective)
    safe_files = ", ".join(_protect(f) for f in files) if files else "(declare with --files)"
    ok = True
    ok &= _create_if_absent(os.path.join(base, "STATE.md"),
        "# Thread: %s\n\n## Objective\n%s\n\n## Fence (files this thread may write)\n"
        "%s\n\n## Plan and next intent\n- next: (write the next intent BEFORE acting)\n"
        % (safe_name, safe_objective, safe_files))
    ok &= _create_if_absent(os.path.join(base, "inbox.md"),
        "# Inbox for %s\nDirectives from the chief. Regenerated by `send`.\n\n" % safe_name)
    ok &= _create_if_absent(os.path.join(base, "outbox.md"),
        "# Outbox from %s\nAdvancement for the chief. Appended by `checkpoint`.\n\n" % safe_name)
    # A VIEW from minute one (bm_store.render_digest of a record with no
    # checkpoint yet), not a hand-formatted template that could drift from
    # what `checkpoint` regenerates later.
    ok &= _create_if_absent(os.path.join(base, "digest.md"), digest_text)
    if not ok:
        _out("START FAILED: the work record was claimed but this thread's files "
             "could not all be written (permissions or disk).")
        _out("  lifecycle %s stays ACTIVE and fenced; fix the disk issue and use "
             "`park`/`resume` or `adopt` to reconcile it." % rec.lifecycle_uuid)
        sys.exit(2)
    _out("thread '%s' created at %s (lifecycle %s, session %s)"
         % (name, base, rec.lifecycle_uuid, rec.session_id))
    _out("  the thread session should read STATE.md + inbox.md, and write outbox.md "
         "via `checkpoint`")


def cmd_checkpoint(argv):
    bs = _store()
    root = _require_root()
    if not argv:
        _out("usage: checkpoint <thread> [--next TEXT] [--blockers TEXT] "
             "[--files-note TEXT] [--body TEXT] [--topic T] [--decision TEXT] "
             "[--lifecycle PREFIX]")
        sys.exit(2)
    name = argv[0]
    kv = _parse_kv(argv[1:])
    # GATE 5 (release-blockers spec, 2026-07-26): reproduced with
    # `checkpoint X --note "..."`, which reported success and stored
    # nothing -- there is no --note flag (the intended flag is
    # --files-note), and the unrecognized key was silently dropped.
    _reject_unknown_flags("checkpoint", kv,
        ("next", "blockers", "files-note", "body", "topic", "decision", "lifecycle"))
    next_intent = " ".join(kv.get("next", []))
    blockers = " ".join(kv.get("blockers", []))
    files_note = " ".join(kv.get("files-note", []))
    body = " ".join(kv.get("body", []))
    topic = " ".join(kv.get("topic", []))
    decision = " ".join(kv.get("decision", []))
    lifecycle_prefix = " ".join(kv.get("lifecycle", [])) or None
    decisions = [(topic, decision)] if decision else None
    store = bs.Store(root, create=False)
    try:
        rec = _find_record(store, name, states=("active",), lifecycle_prefix=lifecycle_prefix)
        seq = store.checkpoint(rec["lifecycle_uuid"], rec["version"], next_intent,
                                blockers=blockers, files_note=files_note, body=body,
                                decisions=decisions)
        digest_text = store.render_digest(rec["lifecycle_uuid"])
    finally:
        store.close()
    _refresh_root_view(root)
    base = _thread_dir(root, name, rec["lifecycle_uuid"])
    if not _atomic_write(os.path.join(base, "digest.md"), digest_text):
        _warn("bm_threads: checkpoint %d saved in the store, but this thread's "
              "digest.md view could not be refreshed on disk." % seq)
    if next_intent or decision:
        safe_next = _protect(next_intent)
        safe_dec = _protect(decision)
        line = "- %s %s%s\n" % (now()[:16], ("%s | " % safe_dec) if safe_dec else "",
                                 ("next: " + safe_next) if safe_next else "")
        try:
            with io.open(os.path.join(base, "outbox.md"), "a", encoding="utf-8") as f:
                f.write(line)
        except OSError:
            _warn("bm_threads: checkpoint %d saved, but the outbox line for '%s' "
                  "could not be written." % (seq, name))
    _out("checkpoint %d recorded for '%s' (version %s)"
         % (seq, name, rec["version"] + 1))


