def cmd_send(argv):
    """Chief -> thread. inbox.md is fully regenerated from the store's
    directives table (already redacted by dump()'s default-deny), never
    hand-appended: a view can never drift from what it is a view OF."""
    bs = _store()
    root = _require_root()
    if len(argv) < 2:
        _out("usage: send <thread> <message...>")
        sys.exit(2)
    name = argv[0]
    text = " ".join(argv[1:])
    store = bs.Store(root, create=False)
    try:
        rec = _find_record(store, name, states=("active",))
        seq = store.send(rec["lifecycle_uuid"], text)
        data = store.dump()
    finally:
        store.close()
    directives = sorted((r for r in data["directives"]
                          if r["lifecycle_uuid"] == rec["lifecycle_uuid"]),
                         key=lambda r: r["seq"])
    lines = ["- [%s] %s" % (r["created_at"], r["text"]) for r in directives]
    body = ("# Inbox for %s\nDirectives from the chief. Regenerated by `send`.\n\n%s\n"
            % (_protect(name), "\n".join(lines)))
    base = _thread_dir(root, name, rec["lifecycle_uuid"])
    if not _atomic_write(os.path.join(base, "inbox.md"), body):
        _warn("bm_threads: directive %d saved in the store, but inbox.md for '%s' "
              "could not be refreshed on disk." % (seq, name))
    _refresh_root_view(root)
    _out("sent to '%s' (directive %d)" % (name, seq))


def cmd_dashboard(argv):
    """The command center: every record's state on one screen, exactly what
    `off` would drain. render_state_md already redacted every field; print
    it through the pre-rendered path so its own structure survives intact."""
    bs = _store()
    root, source = _resolve_root()
    if root is None:
        _out("BROTHERMODE THREADS  (no project root found here or above)")
        _out("  run `on` to start one, or set BROTHERMODE_ROOT.")
        return
    d = _load_mode(root)
    _out("BROTHERMODE THREADS  mode=%s  cap=%d  root=%s (via %s)"
         % (d.get("mode", "off").upper(), bs.MAX_ACTIVE_PERSISTENT, root, source))
    try:
        _out_prerendered(bs.render_state_md(root), end="")
    except bs.OwnershipRefused as e:
        if e.reason == "no-store":
            # No store to refresh a view against either: refreshing here
            # would just re-hit the same "no-store" refusal inside
            # _refresh_root_view and print a redundant, confusing warning
            # underneath this already-graceful message (a NEW warning this
            # command never used to print). Advisory commands fail open
            # with ONE plain message, not two.
            _out("  no store yet. `on` then `start <feature>` to begin.")
            return
        raise
    except bs.StoreCorrupt as e:
        _out("  STORE CORRUPT: %s" % (e,))
        return
    _refresh_root_view(root)


def _transition_cmd(argv, to_state, usage, needs_evidence=False):
    bs = _store()
    root = _require_root()
    if not argv:
        _out("usage: %s" % usage)
        sys.exit(2)
    name = argv[0]
    kv = _parse_kv(argv[1:])
    _reject_unknown_flags(to_state, kv, ("session", "note", "evidence", "lifecycle"))
    session_id = " ".join(kv.get("session", []))
    note = " ".join(kv.get("note", []))
    evidence = " ".join(kv.get("evidence", []))
    lifecycle_prefix = " ".join(kv.get("lifecycle", [])) or None
    if needs_evidence and not evidence.strip():
        _out("%s: --evidence is required (the check_cmd result)" % to_state)
        sys.exit(2)
    source_states = _LEGAL_SOURCE_STATES.get(to_state)
    store = bs.Store(root, create=False)
    try:
        rec = _find_record(store, name, states=source_states, lifecycle_prefix=lifecycle_prefix)
        result = store.transition(rec["lifecycle_uuid"], rec["version"], to_state,
                                   session_id=session_id, note=note, evidence=evidence)
    finally:
        store.close()
    _refresh_root_view(root)
    _out("%s: '%s' (lifecycle %s) is now %s at version %s"
         % (to_state, name, result.lifecycle_uuid, result.state, result.version))


