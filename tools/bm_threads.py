#!/usr/bin/env python3
"""BrotherMode thread mode: persistent feature threads with a chief command center.

WHY THIS EXISTS
  One session that builds everything fills its context with the detail of every
  feature at once, then compacts, and coordination detail is what gets summarized
  away. Thread mode splits the work the way a small company does: one chief who
  only coordinates (so its context stays small and it almost never compacts), and
  one persistent thread per key feature that keeps its own deep domain context for
  days instead of re-learning the same architecture every morning.

WHY THIS FILE IS THIN (Phase 3 rewire, ratified spec 2026-07-26)
  Every ownership and lifecycle fact a thread has (is it active, who holds it,
  what files does it fence, what did it last say) now lives in exactly ONE place:
  bm_store.py's transactional sqlite store. This module is a CLI wrapper around
  that store, nothing more: it never invents its own notion of "active", it never
  keeps a second copy of a record's state, and it never trusts the working
  directory to mean anything (every command resolves the project root through
  bm_store.resolve_root/require_root, the same one canonical root every other
  BrotherMode tool uses). The V1 shape (two JSON registries, a reusable name as
  identity, a silent takeover on re-claim) is gone, not shimmed: the old
  registry module is deleted, and nothing in this file reads or writes it.

THE CONTRACT (three files per thread, so coordination needs no new infrastructure)
  threads/<name>-<lifecycle8>/STATE.md   the thread's own working plan (human-owned)
  threads/<name>-<lifecycle8>/inbox.md   directives INTO the thread. A VIEW of the
                                         store's directives table; only `send`
                                         regenerates it.
  threads/<name>-<lifecycle8>/outbox.md  advancement OUT of the thread, appended by
                                         `checkpoint`.
  threads/<name>-<lifecycle8>/digest.md  a VIEW of the store's handover digest for
                                         this lifecycle, regenerated by `checkpoint`
                                         (and seeded by `start`).
  The directory name is keyed by LIFECYCLE, not just name (bm_store.thread_dir_name),
  so a name that is reused after a park/adopt can never inherit the previous
  lifecycle's working files.

REVERSIBILITY IS THE POINT (founder requirement, 2026-07-24)
  Thread mode must be switchable OFF mid-project with no chaos and no lost context.
  `off` PARKS every ACTIVE, PERSISTENT record and writes its handover in the SAME
  store transaction (LOOP P12), so the two can never come apart. The project's
  root STATE.md renders the undelivered handovers as generated text; it is a
  view, not the place they live. Nothing is deleted, every thread stays resumable
  via `resume`, and the chief continues solo with zero re-exploration. A retry
  cannot duplicate a handover (UNIQUE on the lifecycle plus the content
  fingerprint), and a refused park writes nothing at all.

FAILURE POLICY (matches bm_store.py's two explicit policies)
  Ownership and lifecycle commands (on/off/start/checkpoint/decide/send/park/
  resume/complete/adopt) FAIL CLOSED: a refusal from the store (or from this
  module's own name resolution) is reported and the command exits non-zero.
  Nothing here silently swallows a store refusal into a fake "success". Advisory
  commands (dashboard/recommend) FAIL OPEN: they degrade to a plain message
  rather than raise, because a founder checking status must never be blocked by
  it.

INVARIANTS
  - No network. No subprocess. Pure file I/O plus the store's own sqlite access.
  - Nothing auto-flips: `recommend` only PRINTS advice; only the founder runs
    `on` or `off`.
  - The cap on active persistent records (3) is enforced by the store itself
    (bm_store.MAX_ACTIVE_PERSISTENT), not re-implemented here: one primitive,
    not two copies that can drift apart.
"""
